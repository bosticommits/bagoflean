HEADER = [
    "-- GENERATED by art/blender/seasonal_actors.py from the Blender designs of the limited seasonal",
    "-- actors (Actors.Limited). Do not edit by hand: change the shapes there and run it again. Each",
    "-- actor is a list of shapes in studs, feet on y = 0, facing -Z. ActorModels builds them as parts",
    "-- until the Blender meshes are imported.",
]

INK = "#1E1630"
GOLD = "#F5B82E"
WHITE = "#FFFFFF"

# --- The shared body --------------------------------------------------------------------------
# Blender studs: Z up, facing -Y, feet on Z = 0. Shoulders at 3.9, the chest's front at y = -0.5
# (where ActorModels pins the Award-Winning medal), the head from 3.9 to 5.5.
SHOULDER = 3.9
HEAD_Z = 4.7
FACE_Y = -0.78
HAND = (1.38, -0.05, 2.07)  # right hand (the figure's right is +x); the left is mirrored


def body(skin, shirt, pants, shoes, sleeves=None, legs=None, gloves=None, head=True):
    """Legs, hips, torso, arms and hands, and a rounded head unless the actor brings its own."""
    sleeves = sleeves or shirt
    shapes = [
        *pair(
            E((0.4, -0.14, 0.2), (0.34, 0.5, 0.2), shoes),
            B((0.4, 0, 1.1), (0.66, 0.72, 1.8), legs or pants, bevel=0.2),
            G((1.12, 0, 3.55), (0, -10, 0), B((0, 0, -0.68), (0.56, 0.62, 1.5), sleeves, bevel=0.22), E((0, -0.04, -1.5), (0.3, 0.3, 0.3), gloves or skin)),
        ),
        B((0, 0, 2.08), (1.5, 0.9, 0.5), pants, bevel=0.2),
        B((0, 0, 2.95), (1.7, 1.0, 1.9), shirt, bevel=0.3),
    ]
    if head:
        shapes.append(B((0, 0, HEAD_Z), (1.7, 1.55, 1.6), skin, bevel=0.45))
    return shapes


def face_eyes(z=4.8, x=0.36, iris=None, look=(0, 0)):
    return [*eye((x, FACE_Y, z), iris=iris, look=look), *eye((-x, FACE_Y, z), iris=iris, look=look)]


def grin(z=4.3, width=0.4):
    """A wide toothy grin: a white band of teeth with an ink rim."""
    return [
        E((0, FACE_Y - 0.03, z + 0.02), (width, 0.05, 0.12), WHITE, outline=True),
        B((0, FACE_Y - 0.08, z), (width * 1.4, 0.02, 0.025), "#C9B8B0", bevel=0.005, outline=False),
    ]


def smile(z=4.3, width=0.3, mouth="#5A1E28", lean=0.0):
    """A closed smile: an ink curve, low in the middle and up at the corners."""
    return [
        E((lean, FACE_Y - 0.03, z), (width * 0.75, 0.04, 0.05), mouth, outline=False),
        E((lean + width * 0.82, FACE_Y - 0.03, z + 0.06), (width * 0.3, 0.04, 0.045), mouth, rot=(0, -35, 0), outline=False),
        E((lean - width * 0.82, FACE_Y - 0.03, z + 0.06), (width * 0.3, 0.04, 0.045), mouth, rot=(0, 35, 0), outline=False),
    ]


def heart(at, size, color, neon=False, outline=True, rot=(0, 0, 0)):
    """A heart facing -Y: two round lobes over a point (a box turned on its corner)."""
    s = size
    return G(
        at,
        rot,
        E((0.28 * s, 0, 0.12 * s), (0.3 * s, 0.12 * s, 0.3 * s), color, outline=outline, neon=neon),
        E((-0.28 * s, 0, 0.12 * s), (0.3 * s, 0.12 * s, 0.3 * s), color, outline=outline, neon=neon),
        B((0, 0, -0.14 * s), (0.5 * s, 0.22 * s, 0.5 * s), color, rot=(0, 45, 0), bevel=0.04 * s, outline=outline, neon=neon),
    )


