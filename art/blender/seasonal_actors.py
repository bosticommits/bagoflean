"""Limited seasonal actors: one toy figure per seasonal Film Festival (Actors.Limited).

  pumpkin_phantom.fbx  The Pumpkin Phantom  Fright Night (Horror): a caped gentleman with a
                                             glowing carved-pumpkin head, top hat and lantern
  jingle_jester.fbx    Jingle Jester        Holiday (Comedy): a grinning jester in a two-point
                                             belled hat, striped scarf and a string of lights
  cupid_crooner.fbx    Cupid Crooner        Love Story (Romance): a pink-tux crooner with heart
                                             sunglasses, little wings and a heart microphone
  heatwave_hero.fbx    Heatwave Hero        Summer Blockbuster (Action): a sunglasses action hero
                                             in a beach shirt, a surfboard on his back

They share the actors' proportions (feet on the ground, shoulders at 3.9 studs, a big head on top,
about 5.5 studs before hats) so they stand on a lot's pedestal and fill a Collection card like the
other actors, and the Shiny and Award-Winning effects land in the same places. The shapes and
the outline style are the mascots' (art/blender/mascots.py): rounded toy shapes with a thick dark
rim.

The same shapes are written to src/shared/Models/SeasonalShapes.luau, which the game builds as
parts until the meshes are imported (art/README.md), so this Blender design is the one source.

Run from the repo root with Blender, or with the `bpy` package (see mmkit.py):
  python -c "import bpy, runpy, sys; runpy.run_path(sys.argv[1], run_name='__main__')" art/blender/seasonal_actors.py
Writes art/exports/<actor>.fbx, art/previews/seasonal_actors.png (the line-up) and one
art/previews/seasonal_<name>.png each. Set MASCOT_SAMPLES for quicker test renders.
"""

